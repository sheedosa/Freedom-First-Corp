#!/usr/bin/env node
/**
 * Generates `.pages.yml` — the Pages CMS (pagescms.org) schema — from the actual
 * content JSON, so every editable field is covered and the config cannot drift
 * out of sync with the data.
 *
 * Re-run after changing the shape of anything in `content/<locale>/*.json`:
 *   npm run cms:config
 *
 * The insight-article collections and the media library are declared by hand
 * below (they are markdown, not JSON, and need select/rich-text field types).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LOCALES = [
  { code: 'en', name: 'English' },
  { code: 'ar', name: 'Arabic' },
  { code: 'es', name: 'Spanish' },
];
const PAGES = [
  { file: 'home',         label: 'Home page' },
  { file: 'about',        label: 'About page' },
  { file: 'capabilities', label: 'Capabilities page' },
  { file: 'approach',     label: 'Approach page' },
  { file: 'insights',     label: 'Insights page (labels)' },
  { file: 'contact',      label: 'Contact page' },
  { file: 'site',         label: 'Header, footer & shared labels' },
  { file: 'seo',          label: 'SEO titles & descriptions' },
];

/* ── helpers ──────────────────────────────────────────────────────────────── */

const humanize = (key) =>
  key
    .replace(/[-_]/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/^./, (c) => c.toUpperCase())
    .replace(/\bCta\b/g, 'CTA')
    .replace(/\bSeo\b/g, 'SEO')
    .replace(/\bHse\b/g, 'HSE')
    .replace(/\bUrl\b/g, 'URL')
    .replace(/\bId\b/g, 'ID');

const LONG_TEXT = 110;

/** Fields whose value is structural — changing them breaks links or layout. */
const WARN = {
  id: 'Used as the on-page anchor and in menu links. Do not change.',
  href: 'Link target. Must match a real page or anchor, e.g. /about or /capabilities#upstream.',
  link: 'Link target. Must match a real page or anchor.',
  ctaLink: 'Link target. Must match a real page or anchor.',
  code: 'Language code used by the site. Do not change.',
  name: 'Form field key. Do not change.',
  type: 'Form input type. Do not change.',
  coordinates: 'Map pin position as [longitude, latitude]. Two numbers.',
};

const isImage = (key, value) =>
  typeof value === 'string' && (/^\/images\//.test(value) || /image$/i.test(key));

const yamlStr = (s) => {
  const str = String(s);
  return /^[A-Za-z0-9 ._/·&(),'-]+$/.test(str) && !/^[-?:,[\]{}#&*!|>'"%@`]/.test(str)
    ? `'${str.replace(/'/g, "''")}'`
    : JSON.stringify(str);
};

/** Builds a Pages CMS field definition for one JSON value. */
const toField = (key, value) => {
  const f = { name: key, label: humanize(key) };
  const note = WARN[key];

  if (Array.isArray(value)) {
    f.list = true;
    const first = value[0];
    if (first !== undefined && typeof first === 'object' && !Array.isArray(first)) {
      // Union the keys across all items so an optional key (e.g. nav `dropdown`,
      // leadership `bullets`) is still editable.
      const keys = [...new Set(value.flatMap((o) => Object.keys(o)))];
      f.type = 'object';
      f.fields = keys.map((k) => toField(k, value.find((o) => o[k] !== undefined)[k]));
    } else if (typeof first === 'number') {
      f.type = 'number';
    } else {
      f.type = String(first ?? '').length > LONG_TEXT ? 'text' : 'string';
    }
  } else if (value && typeof value === 'object') {
    f.type = 'object';
    f.fields = Object.entries(value).map(([k, v]) => toField(k, v));
  } else if (typeof value === 'boolean') {
    f.type = 'boolean';
  } else if (typeof value === 'number') {
    f.type = 'number';
  } else if (isImage(key, value)) {
    f.type = 'image';
  } else {
    f.type = String(value).length > LONG_TEXT || String(value).includes('\n') ? 'text' : 'string';
  }

  if (note) f.description = note;
  return f;
};

/** Serialises a field tree to YAML at the given indent. */
const fieldsToYaml = (fields, indent) => {
  const pad = ' '.repeat(indent);
  const out = [];
  for (const f of fields) {
    out.push(`${pad}- name: ${yamlStr(f.name)}`);
    out.push(`${pad}  label: ${yamlStr(f.label)}`);
    out.push(`${pad}  type: ${f.type}`);
    if (f.list) out.push(`${pad}  list: true`);
    if (f.description) out.push(`${pad}  description: ${yamlStr(f.description)}`);
    if (f.fields) {
      out.push(`${pad}  fields:`);
      out.push(fieldsToYaml(f.fields, indent + 4));
    }
  }
  return out.join('\n');
};

/* ── hand-written blocks ──────────────────────────────────────────────────── */

const HEADER = `# Pages CMS schema — https://pagescms.org
#
# GENERATED by scripts/generate-cms-config.mjs from the content JSON.
# Re-run \`npm run cms:config\` after changing the shape of content/<locale>/*.json.
# The insight-article collections and media block below are maintained by hand.
#
# Editing guide for content authors: docs/CMS-GUIDE.md

media:
  input: public/images
  output: /images
  extensions: [jpg, jpeg, png, webp, svg, gif, avif]
  categories: [image]

content:`;

const articleCollection = ({ code, name }) => `
  - name: insights-${code}
    label: 'Insight articles — ${name}'
    type: collection
    path: content/insights/${code}
    filename: '{fields.title}.md'
    format: yaml-frontmatter
    view:
      primary: title
      fields: [title, category, order, date]
      sort: [order, date, title]
    fields:
      - name: title
        label: Title
        type: string
        required: true
        description: 'Shown on the article page and on its card. Also sets the web address for a new article.'
      - name: category
        label: Category
        type: select
        required: true
        default: companyUpdates
        description: 'Controls which filter tab the article appears under on the Insights page.'
        options:
          values:
            - { value: emergingMarkets, label: 'Emerging Markets' }
            - { value: fieldExecution, label: 'Field Execution' }
            - { value: companyUpdates, label: 'Company Updates' }
      - name: order
        label: 'Position in list'
        type: number
        required: true
        default: 1
        description: 'Lower numbers appear first on the Insights page. 1 is the top-left card.'
      - name: date
        label: 'Publication date'
        type: date
        required: true
        options:
          format: yyyy-MM-dd
        description: 'Used for search-engine indexing.'
      - name: image
        label: 'Card image (square)'
        type: image
        description: 'Square thumbnail on the Insights grid. Leave empty to show an "image coming soon" tile.'
      - name: banner
        label: 'Banner image (wide)'
        type: image
        description: 'Wide image behind the article title, about 1500x450. Falls back to the card image.'
      - name: seoTitle
        label: 'Search-engine title'
        type: string
        description: 'Title shown in Google results. Aim for under 60 characters.'
      - name: seoDescription
        label: 'Search-engine description'
        type: text
        description: 'Summary shown in Google results and on llms.txt. Aim for 150-160 characters.'
      - name: published
        label: Published
        type: boolean
        default: true
        description: 'Turn off to hide the article from the website without deleting it.'
      - name: body
        label: 'Article body'
        type: rich-text
        description: 'The article itself. Leave empty to show the card as "Coming soon" without a readable page.'
`;

/* ── build ────────────────────────────────────────────────────────────────── */

const out = [HEADER];

// Articles first — the section the client will use most.
for (const loc of LOCALES) out.push(articleCollection(loc));

for (const loc of LOCALES) {
  for (const page of PAGES) {
    const rel = `content/${loc.code}/${page.file}.json`;
    const json = JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
    const fields = Object.entries(json).map(([k, v]) => toField(k, v));
    out.push(
      [
        '',
        `  - name: ${loc.code}-${page.file}`,
        `    label: ${yamlStr(`${loc.code.toUpperCase()} · ${page.label}`)}`,
        `    path: ${rel}`,
        '    type: file',
        '    format: json',
        '    fields:',
        fieldsToYaml(fields, 6),
      ].join('\n'),
    );
  }
}

fs.writeFileSync(path.join(ROOT, '.pages.yml'), out.join('\n') + '\n');

const lines = out.join('\n').split('\n').length;
console.log(
  `generate-cms-config: .pages.yml written — ${LOCALES.length} article collections + ${LOCALES.length * PAGES.length} page files (${lines} lines)`,
);
