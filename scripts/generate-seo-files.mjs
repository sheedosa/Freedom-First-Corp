#!/usr/bin/env node
/**
 * Regenerates the SEO files that can't read the content collection at runtime:
 *
 *   • public/sitemap.xml   — static routes + every published insight article
 *   • public/llms.txt      — the "Notable insights" list at the end of the file
 *
 * Runs automatically as `prebuild`, so an article published through the CMS is
 * indexed by the next deploy without anyone editing these files by hand. Both
 * outputs are committed, which keeps them reviewable in a diff.
 *
 * Run manually with: npm run seo
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE_URL = 'https://www.freedomfirstglobal.com';
const BASE_LOCALE = 'en';

/**
 * Static routes. `lastmod` is declared rather than derived: stamping every page
 * with the build date on each deploy would tell crawlers that unchanged pages
 * keep changing. Bump a date here when you meaningfully revise that page.
 */
const STATIC_ROUTES = [
  { path: '/',             lastmod: '2026-06-04', changefreq: 'weekly',  priority: '1.0' },
  { path: '/about',        lastmod: '2026-06-04', changefreq: 'monthly', priority: '0.8' },
  { path: '/capabilities', lastmod: '2026-06-04', changefreq: 'monthly', priority: '0.9' },
  { path: '/approach',     lastmod: '2026-06-04', changefreq: 'monthly', priority: '0.8' },
  { path: '/insights',     lastmod: '2026-06-04', changefreq: 'weekly',  priority: '0.7' },
  { path: '/contact',      lastmod: '2026-06-04', changefreq: 'monthly', priority: '0.7' },
];

/** Frontmatter reader — mirrors src/content/articles.ts, kept deliberately small. */
const parseFrontmatter = (src) => {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(src.replace(/^﻿/, ''));
  if (!m) return { data: {}, body: src };
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z0-9_]+)\s*:\s*(.*)$/.exec(line.trim());
    if (!kv) continue;
    let v = kv[2].trim();
    if (/^"[\s\S]*"$/.test(v)) v = v.slice(1, -1).replace(/\\"/g, '"').replace(/\\n/g, '\n').replace(/\\\\/g, '\\');
    else if (/^'[\s\S]*'$/.test(v)) v = v.slice(1, -1).replace(/''/g, "'");
    else if (v === 'true' || v === 'false') v = v === 'true';
    else if (v !== '' && /^-?\d+(\.\d+)?$/.test(v)) v = Number(v);
    data[kv[1]] = v;
  }
  return { data, body: m[2] };
};

const insightsDir = path.join(ROOT, 'content', 'insights', BASE_LOCALE);
if (!fs.existsSync(insightsDir)) {
  console.error(`generate-seo-files: missing ${path.relative(ROOT, insightsDir)}`);
  process.exit(1);
}

const articles = fs
  .readdirSync(insightsDir)
  .filter((f) => f.endsWith('.md'))
  .map((file) => {
    const slug = file.replace(/\.md$/, '');
    const { data, body } = parseFrontmatter(fs.readFileSync(path.join(insightsDir, file), 'utf8'));
    return {
      slug,
      title: typeof data.title === 'string' ? data.title : slug,
      description: typeof data.seoDescription === 'string' ? data.seoDescription : '',
      date: typeof data.date === 'string' ? data.date : '',
      order: typeof data.order === 'number' ? data.order : Number.MAX_SAFE_INTEGER,
      // Teasers (frontmatter but no body) and drafts stay out of both files.
      indexable: data.published !== false && body.trim().length > 0,
    };
  })
  .filter((a) => {
    if (!a.indexable) console.log(`  skipped (draft or teaser): ${a.slug}`);
    return a.indexable;
  })
  .sort((a, b) => a.order - b.order || b.date.localeCompare(a.date) || a.title.localeCompare(b.title));

if (!articles.length) console.warn('generate-seo-files: no publishable articles found');

/* ── sitemap.xml ──────────────────────────────────────────────────────────── */

const xmlEscape = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const urlEntry = ({ loc, lastmod, changefreq, priority }) =>
  [
    '  <url>',
    `    <loc>${xmlEscape(loc)}</loc>`,
    ...(lastmod ? [`    <lastmod>${lastmod}</lastmod>`] : []),
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
    '  </url>',
  ].join('\n');

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/generate-seo-files.mjs — do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...STATIC_ROUTES.map((r) =>
    urlEntry({ loc: `${SITE_URL}${r.path === '/' ? '/' : r.path}`, ...r }),
  ),
  ...articles.map((a) =>
    urlEntry({
      loc: `${SITE_URL}/insights/${a.slug}`,
      lastmod: a.date,
      changefreq: 'yearly',
      priority: '0.6',
    }),
  ),
  '</urlset>',
  '',
].join('\n');

fs.writeFileSync(path.join(ROOT, 'public', 'sitemap.xml'), sitemap);

/* ── llms.txt "Notable insights" section ──────────────────────────────────── */

const llmsPath = path.join(ROOT, 'public', 'llms.txt');
const HEADING = '## Notable insights';
const llms = fs.readFileSync(llmsPath, 'utf8');
const start = llms.indexOf(HEADING);

if (start === -1) {
  console.warn(`generate-seo-files: "${HEADING}" not found in public/llms.txt — left unchanged`);
} else {
  // The section runs to the next "## " heading, or to end of file.
  const after = llms.indexOf('\n## ', start + HEADING.length);
  const bullets = articles
    .map((a) => `- [${a.title}](${SITE_URL}/insights/${a.slug})${a.description ? `: ${a.description}` : ''}`)
    .join('\n');
  const section = `${HEADING}\n\n${bullets}\n`;
  fs.writeFileSync(llmsPath, llms.slice(0, start) + section + (after === -1 ? '' : llms.slice(after + 1)));
}

console.log(
  `generate-seo-files: ${STATIC_ROUTES.length} static routes + ${articles.length} articles → public/sitemap.xml, public/llms.txt`,
);
